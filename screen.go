func draw(pix *[16]int64) func(x, y int) image.Image {
	return func(_, _ int) image.Image {
		var onOff color.Color

		for y := 0; y < 16; y++ {
			for x := 0; x < 32; x++ {
				onOff = color.Transparent

				pow := int64(math.Pow(2, float64(31-x)))
				if (*pix)[y]&pow == pow {
					onOff = color.NRGBA{R: 0, G: 0, B: 0, A: 0xcc}
				}

				img.Set(x, y, onOff)
			}
		}

		return img
	}
}
